def topic_brief(topic: str) -> dict:
    brief = BRIEFS.get(topic, DEFAULT)
    return {
        "topic": topic,
        "title": brief["title"],
        "what": brief["what"],
        "steps": list(brief["steps"]),
        "watch": brief["watch"],
    }


def list_topic_cards() -> list[dict]:
    counts: dict[str, int] = {}
    order: list[str] = []
    for problem in all_problems():
        counts[problem.topic] = counts.get(problem.topic, 0) + 1
        if problem.topic not in order:
            order.append(problem.topic)
    cards = []
    for name in order:
        card = topic_brief(name)
        card["count"] = counts[name]
        cards.append(card)
    return cards


def retry_how(problem: Problem, tries: int) -> str:
    if tries < 2:
        return ""
    parts = [
        "Ты уже проверял эту задачу. Не переписывай всё подряд: исправь один шаг из «Что сделать» и нажми «Проверить» снова."
    ]
    if tries >= 3:
        recipe = RECIPES.get(problem.topic)
        if recipe:
            parts.append("Разбор ещё проще: " + recipe)
        else:
            parts.append("Возьми пример из условия, пройди его на бумаге и сравни каждый print.")
    return " ".join(parts)
