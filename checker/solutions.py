def _annotated_lines(source: str) -> list[dict[str, Any]]:
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return [{"line": n, "code": line, "purpose": "Строка программы."} for n, line in enumerate(source.splitlines(), 1)]
    purposes: dict[int, tuple[int, str]] = {}

    def note(line: int | None, priority: int, text: str) -> None:
        if not line:
            return
        current = purposes.get(line)
        if current is None or priority >= current[0]:
            purposes[line] = (priority, text)

    for node in ast.walk(tree):
        line = getattr(node, "lineno", None)
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            note(line, 70, "Подключаем инструмент, который нужен решению.")
        elif isinstance(node, ast.FunctionDef):
            note(line, 90, "Описываем отдельный повторно используемый шаг алгоритма.")
        elif isinstance(node, (ast.For, ast.While)):
            note(line, 80, "Перебираем очередные данные и обновляем состояние.")
        elif isinstance(node, ast.If):
            note(line, 80, "Проверяем условие задачи и выбираем нужную ветку.")
        elif isinstance(node, ast.Return):
            note(line, 85, "Возвращаем рассчитанное значение из текущего шага.")
        elif isinstance(node, ast.AugAssign):
            target = ast.unparse(node.target) if hasattr(ast, "unparse") else "накопитель"
            note(line, 62, f"Обновляем накопитель `{target}` новым промежуточным значением.")
        elif isinstance(node, ast.Assign):
            targets = ", ".join(ast.unparse(item) for item in node.targets) if hasattr(ast, "unparse") else "переменную"
            note(line, 55, f"Сохраняем промежуточное значение в `{targets}`.")
        elif isinstance(node, ast.Call):
            name = getattr(node.func, "id", getattr(node.func, "attr", "операцию"))
            if name == "input":
                note(line, 95, "Читаем входные данные.")
            elif name == "open":
                note(line, 95, "Открываем подключённый файл задачи.")
            elif name == "print":
                note(line, 100, "Печатаем требуемый ответ в формате задачи.")
    result = []
    for number, line in enumerate(source.splitlines(), 1):
        stripped = line.strip()
        if not stripped:
            continue
        purpose = "Комментарий поясняет идею следующего шага." if stripped.startswith("#") else purposes.get(number, (0, "Преобразуем данные или сохраняем промежуточный результат."))[1]
        result.append({"line": number, "code": line, "purpose": purpose})
    return result


