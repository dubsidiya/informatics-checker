@lru_cache(maxsize=1)
def _manifest() -> dict[str, str]:
    if not MANIFEST.is_file():
        return {}
    payload = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if not isinstance(payload, list):
        return {}
    result: dict[str, str] = {}
    for item in payload:
        if isinstance(item, dict) and item.get("id") and isinstance(item.get("source"), str):
            result[str(item["id"])] = item["source"]
    return result


def solution_source(problem_id: str) -> str | None:
    return _manifest().get(str(problem_id))


def solution_manifest_size() -> int:
    return len(_manifest())


