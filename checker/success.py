from __future__ import annotations

"""Small, evidence-based reviews for accepted solutions.

Passing tests proves correctness for the checker, not that there is a single
"best" implementation.  These notes therefore only recommend a faster route
when the task tag and the student's visible program support that conclusion.
They never quote an answer from a hidden test.
"""

from dataclasses import dataclass

from checker.facts import CodeFacts, extract_facts
from checker.models import Problem


@dataclass(frozen=True)
class SuccessAdvice:
    praise: str
    speed_tip: str

    def __post_init__(self) -> None:
        if "быстр" not in self.speed_tip.lower():
            object.__setattr__(self, "speed_tip", "Быстрее: " + self.speed_tip)


def success_advice(problem: Problem, source: str) -> SuccessAdvice:
    facts = extract_facts(source)
    tags = set(problem.tags)

    if problem.fast_path and problem.author_created:
        label = "авторскую тренировочную задачу" if problem.author_created else "эту задачу"
        return SuccessAdvice(
            f"Ты решил {label} и прошёл все открытые и скрытые проверки.",
            "Быстрее: " + problem.fast_path,
        )

    # Specific EGE formats come first: their efficient method is stable and
    # understandable, unlike a guess based only on the size of a loop.
    if "ege2" in tags:
        if facts.uses_permutations:
            return SuccessAdvice(
                "Ты перебрал варианты порядка столбцов и проверил их по строкам таблицы — для четырёх переменных это короткий и надёжный перебор.",
                "Быстрее и проще отлаживать: заранее составь только строки, где F = 0, а затем для каждого порядка сразу отбрасывай его на первой несовместимой клетке. Все перестановки хранить не нужно.",
            )
        return SuccessAdvice(
            "Ты получил правильный порядок переменных и проверил ограничение из таблицы.",
            "Для похожих №2 удобно автоматизировать проверку: перебрать 24 порядка столбцов и оставить тот, который подходит ко всем неполным строкам. Это снижает риск ошибки в ручной таблице.",
        )

    if "ege1" in tags:
        return SuccessAdvice("Ты правильно прочитал графовую модель и получил нужную характеристику.", "Быстрее: храни список смежности и выполняй один BFS/DFS за O(N+M), не строя лишние матрицы.")
    if "ege3" in tags:
        return SuccessAdvice("Ты корректно отфильтровал записи таблицы и вычислил агрегат.", "Быстрее: один проход по строкам с int-преобразованием и set/счётчиком заменяет повторные запросы к таблице.")
    if "ege4" in tags:
        return SuccessAdvice("Ты правильно перевёл код между представлениями.", "Быстрее: сохраняй фиксированную длину кода символа и преобразуй всю строку одним выражением, без перебора вариантов.")
    if "ege6" in tags:
        return SuccessAdvice("Ты верно связал команды Черепахи с геометрической фигурой.", "Быстрее: распознай фигуру и используй формулу площади/периметра вместо симуляции каждого шага.")
    if "ege7" in tags:
        return SuccessAdvice("Ты правильно посчитал информационный объём и единицы измерения.", "Быстрее: своди задачу к цепочке вариантов → бит/символ → общий объём → байты и округляй один раз в конце.")
    if "ege10" in tags:
        return SuccessAdvice("Ты точно выделил слова и обработал текстовый файл.", "Быстрее: нормализуй текст один раз и сделай один проход по словам вместо повторного поиска по файлу.")
    if "ege11" in tags:
        return SuccessAdvice("Ты корректно вычислил минимальное кодовое представление.", "Быстрее: найди ceil(log2) для одного объекта, умножь на количество и только в конце переведи биты в байты.")
    if "ege12" in tags:
        return SuccessAdvice("Ты правильно смоделировал последовательные команды Редактора.", "Быстрее: повторяй replace первого вхождения до исчезновения шаблона; не пересматривай строку вручную после каждой позиции.")
    if "ege22" in tags:
        return SuccessAdvice("Ты верно учёл зависимости процессов и параллельное выполнение.", "Быстрее: вычисляй критический путь через finish(ID) с кэшем; не симулируй каждую миллисекунду.")

    if "ege15" in tags:
        return SuccessAdvice(
            "Перебор концов отрезка и контроль формулы дали верный результат.",
            "Быстрее: замени импликацию на `not A or P` и ищи точки, где вся формула могла бы стать ложной. Тогда сразу видно, где отрезок A имеет право лежать; перебор оставь как проверку вывода.",
        )

    if "ege18" in tags:
        if facts.nested_fors:
            return SuccessAdvice(
                "Ты прошёл поле динамикой: каждую клетку посчитал из допустимых предшественников, поэтому не перебираешь все пути.",
                "Твой подход уже нужной сложности O(N²). Если поле большое, держи только предыдущую и текущую строки (и значения для диагонали), а не всю таблицу — память станет O(N).",
            )
        return SuccessAdvice(
            "Решение корректно обрабатывает ходы робота и правила начисления награды.",
            "Для больших полей самый быстрый шаблон — динамика по клеткам: максимум и минимум в клетке берутся только из трёх предшественников. Полный перебор маршрутов растёт слишком быстро.",
        )

    if "ege26" in tags:
        if facts.uses_set:
            return SuccessAdvice(
                "Ты учёл повторы через множества, поэтому одна и та же точка не попадает в ответ дважды.",
                "Решение уже идёт по данным за один проход. Для компактного кода собирай `строка → set(позиции)`, а максимум обновляй после чтения: не нужно заново проходить весь файл для каждой строки.",
            )
        return SuccessAdvice(
            "Ты получил правильный учёт светлых точек и выбор первой строки.",
            "На больших входах не ищи повторы списком: множество даёт быструю проверку `позиция in set`. Храни отдельное множество позиций для каждой строки.",
        )

    if "ege27" in tags:
        return SuccessAdvice(
            "Ты правильно выделил компоненты связных точек, отбросил аномалии и нашёл центры кластеров.",
            "Если координат станет намного больше, не сравнивай новую точку со всеми остальными. Разбей плоскость на клетки размером порога и проверяй только свою и соседние клетки; правило связности при этом не меняется.",
        )

    if "ege17" in tags:
        if facts.nested_fors:
            return SuccessAdvice(
                "Ответ верный, но код рассматривает много сочетаний чисел.",
                "Для соседних пар быстрее один проход: `for i in range(len(data) - 1)`. Он проверяет ровно нужные пары и работает за O(n), а не за O(n²).",
            )
        return SuccessAdvice(
            "Ты правильно обработал данные и условия отбора.",
            "Для задач о соседних парах держи один проход по списку и обновляй ответ сразу: это O(n) и не требует хранить список подходящих пар.",
        )

    if "ege24" in tags:
        return SuccessAdvice(
            "Ты верно обработал строку как последовательность символов.",
            "Самый быстрый и удобный шаблон для №24 — один проход с переменными текущей длины и максимума. Не создавай срезы строк внутри цикла: они добавляют лишнюю работу.",
        )

    if "ege8" in tags:
        return SuccessAdvice(
            "Перебор слов и проверка условия дали правильный ответ.",
            "Не собирай все слова в список: перебирай `product`/`permutations` и сразу проверяй очередное слово. Так память почти не растёт; ранние простые проверки ставь первыми.",
        )

    if "ege16" in tags or "ege23" in tags:
        if "lru_cache" in source or "cache" in source:
            return SuccessAdvice(
                "Ты избежал повторных вычислений: одинаковые состояния не пересчитываются заново.",
                "Этот подход уже быстрый. Для ещё более прозрачной отладки можно выписать значения снизу вверх в массиве, если переходы зависят только от меньших аргументов.",
            )
        return SuccessAdvice(
            "Формула и границы обработаны правильно.",
            "Если в похожей задаче ветвей станет больше, добавь `@lru_cache(None)` или динамический массив: это превращает повторный расчёт одинаковых состояний в один расчёт.",
        )

    if "ege25" in tags:
        return SuccessAdvice(
            "Ты верно отобрал и вывел подходящие числа.",
            "В задачах с маской не перебирай весь огромный диапазон: собери число по фиксированным цифрам маски и перебери только места с `?` или `*`.",
        )

    if facts.nested_fors:
        return SuccessAdvice(
            "Решение прошло все проверки, включая скрытые.",
            "В коде есть вложенные циклы. Для следующей похожей задачи сначала проверь, нельзя ли заменить поиск пар множеством, словарём или одним проходом — это часто снижает O(n²) до O(n).",
        )
    if facts.has_loop:
        return SuccessAdvice(
            "Решение прошло все проверки, включая скрытые.",
            "Цикл здесь уместен. Для более быстрой и понятной версии обновляй ответ прямо в цикле и не создавай промежуточные списки, если они потом нужны только для `len`, `max` или `min`.",
        )
    return SuccessAdvice(
        "Решение прошло все проверки, включая скрытые.",
        "Быстрее здесь не обязательно значит лучше: перед усложнением кода проверь крайние значения, формат вывода и один пример вручную. Если они ясны, текущая короткая версия обычно лучше преждевременной оптимизации.",
    )
