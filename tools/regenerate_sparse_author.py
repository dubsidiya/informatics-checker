def main() -> None:
    items = json.loads(CATALOG.read_text(encoding="utf-8"))
    counters = {topic: 0 for topic in FOCUS}
    for item in items:
        topic = item.get("topic")
        if not item.get("author_created") or topic not in FOCUS:
            continue
        index = counters[topic]
        counters[topic] += 1
        a = FOCUS[topic][index % len(FOCUS[topic])]
        b = FOCUS[topic][(index + 1) % len(FOCUS[topic])]
        c = FOCUS[topic][(index + 2) % len(FOCUS[topic])]
        marker = "Педагогический фокус:"
        statement = str(item.get("statement") or "")
        if marker in statement:
            statement = statement.split(marker, 1)[0].rstrip()
        item["statement"] = statement
        item["mistake_hints"] = [
            {"title": a[0], "detail": a[1], "signal": "always"},
            {"title": b[0], "detail": b[1], "signal": "always"},
            {"title": c[0], "detail": c[1], "signal": "always"},
        ]
        item["fast_path"] = "Быстрее: " + a[2]
    CATALOG.write_text(json.dumps(items, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("enriched", sum(counters.values()), counters)


if __name__ == "__main__":
    main()
